package com.basics.practice;
//A literal is a fixed, constant value written directly in the source code — it represents
// data itself rather than a variable or expression.
//For example:
//int x = 10;       // 10 is an integer literal
//String s = "Hi";  // "Hi" is a string literal

public class LiteralsJava {
    public static void main(String[] args) {
        int x = 50;//50 is an integer
        String name = "Ashwin";
        int abc = 0b101;//this is binary format and will print 5 - 101  writing b  -binary format
        System.out.println(abc);
    }
}
